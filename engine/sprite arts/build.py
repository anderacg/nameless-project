"""Bundle the live sprite and game art scripts into one offline workshop."""
from pathlib import Path
import re
root = Path(__file__).resolve().parent
# Keep wildlife artwork synchronized without loading the world's simulation systems.
repo = root.parent.parent
data = (repo / 'prototype/js/data/critters.js').read_text()
world = (repo / 'prototype/js/world/critters.js').read_text()
a = data.index('const CRITTERS={')
b = data.index('\n};', a) + 3
c = world.index('const CRITTER_MAP={')
d = world.index('// its work in the world', c)
(root / 'catalog-wildlife.js').write_text('/* Generated by build.py from the game wildlife data and drawing functions. */\n' + data[a:b] + '\n' + world[c:d])
monsters = (repo / 'prototype/js/data/monsters.js').read_text()
start = monsters.index('Object.assign(ST,{')
end = monsters.index('});', start) + 3
(root / 'catalog-unit-data.js').write_text('/* Generated from the game monster unit table; no inventory or simulation. */\n' + monsters[start:end])
html = (root / 'index.html').read_text()
html = html.replace('<link rel="stylesheet" href="style.css">', '<style>' + (root / 'style.css').read_text() + '</style>')
def inline(match):
    file = (root / match.group(1)).resolve()
    source = file.read_text().replace('</script', '<\\/script')
    source = re.sub(r'(?m)^[ \t]+$', '', source)
    return '<script>\n' + source + '\n</script>'
html = re.sub(r'<script src="([^"]+)"></script>', inline, html)
(root / 'sprite-workshop.html').write_text(html)
print('Built sprite-workshop.html from the current shared art scripts')
